const missing = Object.keys(zh).filter((key) => !(key in en));
const extra = Object.keys(en).filter((key) => !(key in zh));
if (missing.length || extra.length) {
  throw new Error(`locale key mismatch missing=${missing.join(",")} extra=${extra.join(",")}`);
}

export function formatMessage(template: string, params?: MessageParams) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

export function translate(locale: Locale, key: string, params?: MessageParams) {
  const table = locale === 'zh' ? zh : en;
  return formatMessage(table[key] || en[key] || key, params);
}
